/*
 * Intel / Lantiq WAV500 (gen5b: WAV514/WAV524, PCI ID 1bef:0810)
 * Clean-room hardware register, CHI, and UMI protocol definitions.
 */
#ifndef _WAV500_REGS_H_
#define _WAV500_REGS_H_

#define WAV500_PCI_VENDOR_ID		0x1bef
#define WAV500_PCI_DEVICE_ID_GEN5B	0x0810

/* BAR0 size is 8 MiB (0x00800000) */
#define WAV500_BAR0_MIN_LEN		0x00800000

/* Firmware IRAM / SRAM load windows inside BAR0 */
#define WAV500_UMAC_IRAM_OFF		0x00300000
#define WAV500_UMAC_IRAM_MAX_SIZE	0x00058000
#define WAV500_LMAC_IRAM_OFF		0x00380000
#define WAV500_LMAC_IRAM_MAX_SIZE	0x00028000
#define WAV500_TX_SENDER_OFF		0x002f0000
#define WAV500_TX_SENDER_MAX_SIZE	0x00009000
#define WAV500_HOST_IF_OFF		0x002ec000
#define WAV500_HOST_IF_MAX_SIZE		0x00001800
#define WAV500_RX_HANDLER_OFF		0x002e8000
#define WAV500_RX_HANDLER_MAX_SIZE	0x00002000

/* Upper MAC (UMAC) & Lower MAC (LMAC) system control registers */
#define WAV500_UMAC_PLL_CFG0		0x0037c040
#define WAV500_UMAC_PLL_CFG1		0x0037c044
#define WAV500_UMAC_PLL_CTRL		0x0037c048
#define WAV500_UMAC_PLL_STAT		0x0037c050
#define WAV500_UMAC_CLK_CTRL		0x0037c058
#define WAV500_UMAC_CHIP_ID		0x0037c060
#define WAV500_UMAC_SEC_UNLOCK		0x0037c068
#define WAV500_UMAC_CPU_BOOT_CTRL	0x0037c074
#define WAV500_UMAC_B11_CTRL		0x0037c0ac

#define WAV500_LMAC_SEC_UNLOCK		0x003fc068
#define WAV500_LMAC_CPU_BOOT_CTRL	0x003fc074

#define WAV500_SEC_UNLOCK_KEY1		0x0000aaaa
#define WAV500_SEC_UNLOCK_KEY2		0x00005555

/* Subsystem clocks, resets, IRQ, and doorbell */
#define WAV500_PAS_CTL_EN0		0x002e0000
#define WAV500_PAS_CTL_EN1		0x002e0004
#define WAV500_IRQ_STATUS		0x002e01d0
#define WAV500_IRQ_MASK			0x002e01d4
#define WAV500_SOC_RESET_CTRL		0x002a0004
#define WAV500_PCIE_IRQ_EN0		0x002a004c
#define WAV500_PCIE_IRQ_EN1		0x002a0050
#define WAV500_PCIE_MSI_MODE		0x002a00ac
#define WAV500_PCIE_MSI_CTRL		0x002a8050
#define WAV500_IRQ_CLEAR		0x0022002c
#define WAV500_HOST_DOORBELL		0x00220038
#define WAV500_MAC_CTRL_MISC		0x00200300
#define WAV500_PROGMODEL_VER		0x00508040

/* CHI (Common Host Interface) area at SHRAM offset 0 */
#define WAV500_CHI_BASE_OFF		0x00000000
#define WAV500_CHI_BASE_SIZE		0x000000cc
#define WAV500_CHI_MAGIC_OFF		0x000000c8
#define WAV500_CHI_EXT_OFF		0x000000cc
#define WAV500_CHI_MAGIC		0xbeadfeed

/* CHI base word indices (offset / 4) */
#define WAV500_CHI_IND_RING_OFF_IDX	0	/* SHRAM+0x00: FW->Host ring offset */
#define WAV500_CHI_IND_RING_CNT_IDX	1	/* SHRAM+0x04: FW->Host ring entries */
#define WAV500_CHI_REQ_RING_OFF_IDX	2	/* SHRAM+0x08: Host->FW ring offset */
#define WAV500_CHI_REQ_RING_CNT_IDX	3	/* SHRAM+0x0c: Host->FW ring entries */
#define WAV500_CHI_MAN_IND_OFF_IDX	8	/* SHRAM+0x20: MAN_IND BDR offset */
#define WAV500_CHI_MAN_IND_CNT_IDX	9	/* SHRAM+0x24: MAN_IND BDR count */
#define WAV500_CHI_MAN_REQ_OFF_IDX	10	/* SHRAM+0x28: MAN_REQ BDR offset */
#define WAV500_CHI_MAN_REQ_CNT_IDX	11	/* SHRAM+0x2c: MAN_REQ BDR count */

/* CHI TLV extension IDs */
#define WAV500_CHI_EXT_CAL		1
#define WAV500_CHI_EXT_MIPS_CTRL	2
#define WAV500_CHI_EXT_FW_LOG		3
#define WAV500_CHI_EXT_NOF_STA		4
#define WAV500_CHI_EXT_NOF_VAP		5
#define WAV500_CHI_EXT_FW_LOG_BUF	6
#define WAV500_CHI_EXT_STATS_MGR	7

/* BDR slot sizes and ring message types */
#define WAV500_MAN_REQ_SLOT_SIZE	0x1f8	/* 16B hdr + 488B payload */
#define WAV500_MAN_REQ_HDR_SIZE		0x10
#define WAV500_MAN_REQ_PAYLOAD_MAX	0x1e8
#define WAV500_MAN_IND_SLOT_SIZE	0x12c	/* 300 bytes */

#define WAV500_RING_TYPE_MASK		0x1f
#define WAV500_RING_TYPE_MAN_IND	3
#define WAV500_RING_TYPE_MAN_REQ	4
#define WAV500_RING_TYPE_DBG_IND	5
#define WAV500_RING_TYPE_DBG_REQ	6
#define WAV500_RING_TYPE_FW_LOG		9

/* CHI base word indices for data-path ring control blocks (4 x u32 each) */
#define WAV500_CHI_RING_TX_OFF		0x00000050
#define WAV500_CHI_RING_RX_OFF		0x00000068
#define WAV500_CHI_RING_BSS_TX_OFF	0x00000080
#define WAV500_CHI_RING_BSS_RX_OFF	0x00000098

/* UMI Management Request IDs */
#define WAV500_UMI_MAN_SET_MIB_REQ	0x0400
#define WAV500_UMI_MAN_GET_MIB_REQ	0x0401
#define WAV500_UMI_MAN_DOWNLOAD_PM_REQ	0x0402
#define WAV500_UMI_MAN_SET_KEY_REQ	0x0405
#define WAV500_UMI_MAN_SET_WMM_REQ	0x040a
#define WAV500_UMI_MAN_DATA_PATH_INIT	0x040e
#define WAV500_UMI_MAN_SET_CHAN_REQ	0x0412
#define WAV500_UMI_MAN_SET_ANTENNAS_REQ	0x0418
#define WAV500_UMI_MAN_PREPARE_PM_REQ	0x041b
#define WAV500_UMI_MAN_HW_DEP_CFG_REQ	0x041c
#define WAV500_UMI_MAN_VAP_DB_REQ	0x041e
#define WAV500_UMI_MAN_ACTIVATE_REQ	0x041f
#define WAV500_UMI_BSS_SET_BSS_REQ	0x0421
#define WAV500_UMI_MAN_GET_STATS_TBL	0x042e
#define WAV500_UMI_MAN_STA_ADD_REQ	0x043b
#define WAV500_UMI_MAN_STA_REMOVE_REQ	0x043c
#define WAV500_UMI_MAN_SET_BEACON_REQ	0x043d
#define WAV500_UMI_MAN_REQUEST_SID_REQ	0x0442
#define WAV500_UMI_MAN_REMOVE_SID_REQ	0x0443
#define WAV500_UMI_MAN_SET_DEF_KEY_REQ	0x0445
#define WAV500_UMI_MAN_SET_TPC_REQ	0x044e
#define WAV500_UMI_MAN_SET_TPC_CFG_REQ	0x044f
#define WAV500_UMI_MAN_HDK_CONFIG_REQ	0x0450
#define WAV500_UMI_MAN_PRE_ACTIVATE_REQ	0x0452
#define WAV500_UMI_MAN_CALIBRATE_REQ	0x0453
#define WAV500_UMI_MAN_PSDB_FIELDS_REQ	0x0457
#define WAV500_UMI_MAN_PSDB_TABLE_REQ	0x0458
#define WAV500_UMI_MAN_SET_RSSI_CAL_REQ	0x045b
#define WAV500_UMI_MAN_RADIO_MODE_REQ	0x045c
#define WAV500_UMI_MAN_SET_TX_PWR_LIM	0x045f
#define WAV500_UMI_MAN_GET_STATS_DATA	0x0460

/* SHRAM scratch offset for ProgModel chunked download */
#define WAV500_PM_SHRAM_OFF		0x00000014
#define WAV500_PM_CHUNK_MAX		8000

#endif /* _WAV500_REGS_H_ */
